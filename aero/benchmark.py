"""
Benchmark AVL against results published outside this repository.

verify_avl.py checks that the harness is internally consistent and that the physics
is not obviously broken. It cannot catch a systematic error, because every number in
it is generated by the same code being tested. This file is the answer to that: three
checks whose expected values come from somewhere else.

    1. WARREN 12   -- the standard vortex-lattice verification planform. Reference
                      values are published in Mason, "Applied Computational
                      Aerodynamics", ch. 6 (Virginia Tech):
                          CL_alpha = 2.743 /rad
                          Cm_alpha = -3.10 /rad
                      with the NONSTANDARD reference convention that goes with them:
                      reference chord = average chord = 1.0 (not the MAC), and the
                      moment reference point at the WING APEX (not the quarter-MAC).
                      Getting either of those wrong changes Cm_alpha by tens of
                      percent, which is exactly the kind of error this is here to
                      catch.

    2. ELLIPTIC WING -- Prandtl: an elliptically loaded wing has span efficiency
                      e = 1.0 exactly. Any inviscid method that cannot reproduce this
                      is wrong, and the margin by which AVL misses it is a direct
                      readout of lattice resolution error.

    3. GENERATOR AREA -- geometry.py writes Sref/Cref/Bref into the deck header, and
                      AVL echoes them back, so comparing those is circular and proves
                      nothing. AVL also reports the area it computes by integrating
                      the SECTION cards (via the FN surface-forces output). Comparing
                      THAT against the requested S_ref is non-circular, and it is what
                      catches a deck generator whose sweep/chord/span trigonometry is
                      wrong -- the single most likely thing for an agent to get
                      subtly wrong and never notice.

Usage:
    AVL_BIN=/path/to/avl python3 aero/benchmark.py
"""

from __future__ import annotations

import math
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from aero.avl_runner import find_avl, run_case  # noqa: E402
from aero.geometry import write_deck  # noqa: E402

results: list[bool] = []


def check(name: str, ok: bool, detail: str) -> None:
    results.append(ok)
    print(f"[{'PASS' if ok else 'FAIL'}] {name}\n        {detail}")


# ----------------------------------------------------------------------------------
# 1. Warren 12
# ----------------------------------------------------------------------------------

WARREN12_CL_ALPHA = 2.743   # /rad, Mason ACA ch.6
WARREN12_CM_ALPHA = -3.10   # /rad, about the wing apex, cref = average chord


def warren12_deck(n_chord: int = 10, n_span: int = 25) -> str:
    """Warren 12: taper 1/3, LE sweep 53.54 deg, AR = 2*sqrt(2), flat plate.

    root chord 1.5, tip chord 0.5, semispan sqrt(2)
      -> S = 2*sqrt(2), b = 2*sqrt(2), AR = 2*sqrt(2), average chord = 1.0
    No NACA/AFILE card: a flat plate, which is what the reference case is.
    """
    s = math.sqrt(2.0)
    c_root, c_tip = 1.5, 0.5
    x_le_tip = s * math.tan(math.radians(53.54))
    S = (c_root + c_tip) * s
    b = 2.0 * s
    return f"""Warren 12 standard VLM check case
#Mach
0.0
#IYsym IZsym Zsym
0      0     0.0
#Sref     Cref   Bref
{S:.8f}  1.0  {b:.8f}
#Xref Yref Zref   (apex -- nonstandard, but it is what the reference values use)
0.0   0.0  0.0
#CDp
0.0

SURFACE
Wing
#Nchord Cspace Nspan Sspace
{n_chord}  1.0  {n_span}  -2.0
YDUPLICATE
0.0

SECTION
#Xle Yle Zle Chord Ainc
0.0  0.0  0.0  {c_root:.8f}  0.0

SECTION
#Xle Yle Zle Chord Ainc
{x_le_tip:.8f}  {s:.8f}  0.0  {c_tip:.8f}  0.0
"""


def run_warren12(tmp: Path) -> None:
    deck = tmp / "warren12.avl"
    deck.write_text(warren12_deck())

    # Two small alphas, differenced. Small because the reference values are the
    # linearised slopes; AVL is linear in alpha anyway, so this is exact.
    lo = run_case(deck, trim=("alpha", -2.0), timeout_s=60)
    hi = run_case(deck, trim=("alpha", 2.0), timeout_s=60)
    dalpha = math.radians(4.0)

    cla = (hi.CL - lo.CL) / dalpha
    cma = (hi.Cm - lo.Cm) / dalpha

    err_l = abs(cla - WARREN12_CL_ALPHA) / abs(WARREN12_CL_ALPHA)
    err_m = abs(cma - WARREN12_CM_ALPHA) / abs(WARREN12_CM_ALPHA)

    check(
        "Warren 12  CL_alpha",
        err_l < 0.02,
        f"AVL {cla:.4f} /rad  vs published {WARREN12_CL_ALPHA:.4f} /rad "
        f"({err_l * 100:.2f}% off)",
    )
    check(
        "Warren 12  Cm_alpha (about the apex, cref = 1.0)",
        err_m < 0.03,
        f"AVL {cma:.4f} /rad  vs published {WARREN12_CM_ALPHA:.4f} /rad "
        f"({err_m * 100:.2f}% off)",
    )

    # A wrong reference convention is the classic silent error, so demonstrate what it
    # would have cost: the same run reported about the quarter-MAC instead of the apex.
    # MAC and its location for this planform:
    taper = 1.0 / 3.0
    c_root = 1.5
    s = math.sqrt(2.0)
    mac = (2.0 / 3.0) * c_root * (1 + taper + taper**2) / (1 + taper)
    y_mac = (2.0 * s / 6.0) * (1 + 2 * taper) / (1 + taper)
    x_le_mac = y_mac * math.tan(math.radians(53.54))
    x_qmac = x_le_mac + 0.25 * mac
    # Cm about a shifted point, nondimensionalised on the same cref = 1.0:
    cma_qmac = cma + x_qmac * cla / 1.0
    print(
        f"        (for contrast: about the quarter-MAC instead, Cm_alpha would read "
        f"{cma_qmac:+.3f} /rad -- a {abs(cma_qmac - cma) / abs(cma) * 100:.0f}% "
        f"difference from picking the wrong reference point)"
    )


# ----------------------------------------------------------------------------------
# 2. Elliptic wing -> e = 1.0
# ----------------------------------------------------------------------------------

def elliptic_deck(n_span: int = 30, n_chord: int = 8, AR: float = 8.0) -> str:
    """Elliptic planform built from explicit sections, c(y) = c0*sqrt(1-(2y/b)^2),
    with the quarter-chord line straight so the loading is elliptic."""
    b = 4.0
    S = math.pi * b * b / (4.0 * AR)      # ellipse area = pi/4 * b * c0
    c0 = 4.0 * S / (math.pi * b)
    n_sec = 20
    secs = []
    for i in range(n_sec):
        # cosine-clustered stations, stopping just short of the singular tip
        eta = math.sin(0.5 * math.pi * i / (n_sec - 1)) * 0.9995
        y = 0.5 * b * eta
        c = c0 * math.sqrt(max(0.0, 1.0 - eta**2))
        x_le = 0.25 * c0 - 0.25 * c       # straight quarter-chord line
        secs.append(f"SECTION\n{x_le:.8f}  {y:.8f}  0.0  {c:.8f}  0.0\n")
    return (
        f"Elliptic wing (Prandtl: e = 1.0)\n#Mach\n0.0\n"
        f"#IYsym IZsym Zsym\n0 0 0.0\n"
        f"#Sref Cref Bref\n{S:.8f}  {S / b:.8f}  {b:.8f}\n"
        f"#Xref Yref Zref\n0.0 0.0 0.0\n#CDp\n0.0\n\n"
        f"SURFACE\nWing\n#Nchord Cspace Nspan Sspace\n"
        f"{n_chord}  1.0  {n_span}  -2.0\nYDUPLICATE\n0.0\n\n" + "\n".join(secs)
    )


def run_elliptic(tmp: Path) -> None:
    deck = tmp / "elliptic.avl"
    deck.write_text(elliptic_deck())
    r = run_case(deck, trim=("CL", 0.5), timeout_s=90)
    check(
        "Elliptic planform gives Prandtl's e = 1.0",
        abs(r.e - 1.0) < 0.02,
        f"AVL e = {r.e:.4f}  vs theory 1.0000 ({abs(r.e - 1.0) * 100:.2f}% off)",
    )


# ----------------------------------------------------------------------------------
# 3. Non-circular check on the deck generator
# ----------------------------------------------------------------------------------

def avl_computed_area(deck: Path, avl_bin: Path) -> float:
    """Ask AVL for the area it computes by integrating the SECTION cards.

    This deliberately bypasses avl_runner: it needs the FN (surface forces) output,
    which reports the true surface area rather than the Sref written in the header.
    Comparing the two is the only way to test the generator's planform maths without
    grading the generator against itself.
    """
    work = Path(tempfile.mkdtemp(prefix="avl_area_"))
    (work / deck.name).write_text(deck.read_text())
    cmds = f"LOAD {deck.name}\nOPER\nA A 2.0\nX\nFN surf.txt\n\nQUIT\nQUIT\n"
    subprocess.run(
        [str(avl_bin)], cwd=str(work), input=cmds, text=True,
        capture_output=True, timeout=120,
    )
    text = (work / "surf.txt").read_text(errors="replace")

    # The FN file contains TWO tables of per-surface areas: the first referred to
    # Sref/Cref/Bref, the second ("Ssurf, Cave about root LE") referred to each
    # surface's own quantities. The area column is identical in both, so a naive
    # regex over the whole file silently returns exactly twice the real area -- which
    # looks like a 100% geometry error and is really a parsing bug. Take the first
    # table only. Each YDUPLICATE half is its own row, so the rows do need summing.
    head = text.split("Surface Forces (referred to Ssurf")[0]
    body = head.split("n      Area", 1)
    if len(body) < 2:
        raise RuntimeError(f"could not find the FN area table:\n{text[:800]}")
    areas = [float(m) for m in re.findall(r"^\s*\d+\s+(\d+\.\d+)", body[1], re.M)]
    if not areas:
        raise RuntimeError(f"could not read surface areas from FN output:\n{text[:800]}")
    return sum(areas)


def run_generator_check(tmp: Path, avl_bin: Path) -> None:
    cases = [
        (16.0, 10.0, 0.12, 0.0),
        (22.0, 18.0, 0.14, 12.0),
        (9.0, 24.0, 0.10, 5.0),
    ]
    worst = 0.0
    detail = []
    for S_ref, AR, t_c, sweep in cases:
        deck = tmp / f"gen_{S_ref}_{AR}.avl"
        geom = write_deck(deck, S_ref=S_ref, AR=AR, t_c=t_c, sweep_c4=sweep)
        computed = avl_computed_area(deck, avl_bin)
        err = abs(computed - S_ref) / S_ref
        worst = max(worst, err)
        detail.append(
            f"S={S_ref:5.1f} AR={AR:4.1f} sweep={sweep:4.1f}deg -> "
            f"AVL integrates {computed:7.4f} m^2 ({err * 100:+.3f}%), b={geom.span:.3f} m"
        )
    check(
        "Deck generator planform matches the area AVL integrates",
        worst < 0.005,
        "\n        ".join(detail),
    )


def main() -> int:
    try:
        avl_bin = find_avl()
    except Exception as e:  # noqa: BLE001
        print(f"[FAIL] no AVL binary: {e}")
        return 2
    print(f"AVL binary: {avl_bin}\n")

    tmp = Path(tempfile.mkdtemp(prefix="avl_bench_"))
    run_warren12(tmp)
    run_elliptic(tmp)
    run_generator_check(tmp, avl_bin)

    n_fail = results.count(False)
    print(f"\n{len(results) - n_fail}/{len(results)} benchmarks passed")
    return 1 if n_fail else 0


if __name__ == "__main__":
    raise SystemExit(main())
